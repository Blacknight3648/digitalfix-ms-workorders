-- Script V1 para la base de datos Oracle de ms-workorders
CREATE TABLE WORK_ORDERS (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENTE         VARCHAR2(150) NOT NULL,
    SERVICIO        VARCHAR2(200) NOT NULL,
    TECNICO         VARCHAR2(150),
    ESTADO          VARCHAR2(30) NOT NULL,   -- CREADA, ASIGNADA, EN_DESPLAZAMIENTO, EN_EJECUCION, CERRADA, CANCELADA
    FECHA_CREACION  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_WORK_ORDERS_ESTADO ON WORK_ORDERS(ESTADO);
