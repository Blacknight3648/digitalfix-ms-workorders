-- ---------------------------------------------------------------------
-- Ajustes de CLIENTE y PROVEEDOR existentes
-- ---------------------------------------------------------------------
-- Solo aplican si las tablas ya existen (las creó Hibernate antes de esta
-- versión). En una base nueva no existen todavía: Hibernate las crea después
-- con la estructura final, por eso cada paso verifica la columna antes.
DECLARE
    FUNCTION existe_columna(p_tabla VARCHAR2, p_columna VARCHAR2) RETURN BOOLEAN IS
        v_total NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_total
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = p_tabla AND COLUMN_NAME = p_columna;
        RETURN v_total > 0;
    END;
BEGIN
    -- CLIENTE: nombres y apellidos pasan a un solo campo (nombre completo o razón social).
    IF existe_columna('CLIENTE', 'NOMBRES_CLIENTE') THEN
        IF NOT existe_columna('CLIENTE', 'NOMBRE_CLIENTE') THEN
            EXECUTE IMMEDIATE 'ALTER TABLE CLIENTE ADD (NOMBRE_CLIENTE VARCHAR2(150))';
        END IF;
        EXECUTE IMMEDIATE q'[UPDATE CLIENTE
            SET NOMBRE_CLIENTE = TRIM(NOMBRES_CLIENTE || ' ' || APELLIDO_PATERNO_CLIENTE
                                      || NVL2(APELLIDO_MATERNO_CLIENTE, ' ' || APELLIDO_MATERNO_CLIENTE, ''))]';
        EXECUTE IMMEDIATE 'ALTER TABLE CLIENTE MODIFY (NOMBRE_CLIENTE NOT NULL)';
        EXECUTE IMMEDIATE 'ALTER TABLE CLIENTE DROP (NOMBRES_CLIENTE, APELLIDO_PATERNO_CLIENTE, APELLIDO_MATERNO_CLIENTE)';
    END IF;

    -- ID_DIRECCION apuntaba a un almacén de direcciones que nunca existió: se limpia
    -- para que la nueva FK hacia DIRECCION se pueda crear.
    IF existe_columna('CLIENTE', 'ID_DIRECCION') THEN
        EXECUTE IMMEDIATE 'UPDATE CLIENTE SET ID_DIRECCION = NULL';
    END IF;
    IF existe_columna('PROVEEDOR', 'ID_DIRECCION') THEN
        EXECUTE IMMEDIATE 'UPDATE PROVEEDOR SET ID_DIRECCION = NULL';
    END IF;

    -- PROVEEDOR: tipo de proveedor. Los existentes abastecían repuestos, por eso PRODUCTOS.
    IF existe_columna('PROVEEDOR', 'RAZON_SOCIAL_PROVEEDOR') AND NOT existe_columna('PROVEEDOR', 'TIPO_PROVEEDOR') THEN
        EXECUTE IMMEDIATE q'[ALTER TABLE PROVEEDOR ADD (TIPO_PROVEEDOR VARCHAR2(20) DEFAULT 'PRODUCTOS' NOT NULL
            CONSTRAINT CK_PROVEEDOR_TIPO CHECK (TIPO_PROVEEDOR IN ('SERVICIOS', 'PRODUCTOS')))]';
    END IF;
END;
