-- =====================================================================
-- V3: Ubicaciones de Chile (región, comuna, dirección) y ajustes de cliente,
--     proveedor y catálogo de servicios
-- =====================================================================
-- 3FN: DIRECCION guarda solo ID_COMUNA; la región se obtiene por la comuna.
-- Cada cliente y proveedor tiene su propia dirección (CLIENTE.ID_DIRECCION y
-- PROVEEDOR.ID_DIRECCION; las FK las agrega Hibernate con ddl-auto=update).
--
-- Catálogo: 16 regiones (ID = código CUT) y 346 comunas según la división
-- político-administrativa vigente (SUBDERE).

-- Oracle Autonomous ejecuta DML en paralelo por defecto; se desactiva para que
-- los INSERT de comunas puedan leer REGION en la misma transacción.
ALTER SESSION DISABLE PARALLEL DML;

CREATE TABLE REGION (
    ID_REGION        NUMBER(19)    NOT NULL,
    NOMBRE_REGION    VARCHAR2(100) NOT NULL,
    NUMERO_ROMANO    VARCHAR2(5)   NOT NULL,
    ORDEN_GEOGRAFICO NUMBER(10)    NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (ID_REGION),
    CONSTRAINT UK_REGION_NOMBRE UNIQUE (NOMBRE_REGION)
);

CREATE TABLE COMUNA (
    ID_COMUNA     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE_COMUNA VARCHAR2(60) NOT NULL,
    ID_REGION     NUMBER(19)   NOT NULL,
    CONSTRAINT PK_COMUNA PRIMARY KEY (ID_COMUNA),
    CONSTRAINT UK_COMUNA_REGION_NOMBRE UNIQUE (ID_REGION, NOMBRE_COMUNA),
    CONSTRAINT FK_COMUNA_REGION FOREIGN KEY (ID_REGION) REFERENCES REGION (ID_REGION)
);

CREATE TABLE DIRECCION (
    ID_DIRECCION  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_COMUNA     NUMBER(19)    NOT NULL,
    CALLE         VARCHAR2(120) NOT NULL,
    NUMERO        VARCHAR2(10)  NOT NULL,
    DETALLE       VARCHAR2(60),
    REFERENCIA    VARCHAR2(200),
    CODIGO_POSTAL VARCHAR2(7),
    CONSTRAINT PK_DIRECCION PRIMARY KEY (ID_DIRECCION),
    CONSTRAINT FK_DIRECCION_COMUNA FOREIGN KEY (ID_COMUNA) REFERENCES COMUNA (ID_COMUNA),
    CONSTRAINT CK_DIRECCION_CODIGO_POSTAL CHECK (CODIGO_POSTAL IS NULL OR REGEXP_LIKE(CODIGO_POSTAL, '^[0-9]{7}$'))
);

CREATE INDEX IDX_DIRECCION_COMUNA ON DIRECCION (ID_COMUNA);

-- Correlativo del código de servicio (SRV-0001, SRV-0002, ...).
CREATE SEQUENCE SEQ_CODIGO_SERVICIO START WITH 1 INCREMENT BY 1 NOCACHE;

